"""Build a dataset with merged classes: one class per (part, damage_type).

The 18 Roboflow classes split the same damage into Minor/Medium/Major variants
(e.g. Minor-/Medium-/Major-front-bumper-dent), which are visually very close and
limit mAP50. The vision agent only needs `part` and `damage_type` (severity is
computed by the rule in agent.py), so we merge every class into its
(part, damage_type) pair from class_mapping.yaml -> 8 classes.

Images are copied unchanged (DVC deduplicates identical files); only labels change.

Usage (from the repo root):
    python -m agents.vision.merge_classes
"""
import os
import shutil
from collections import Counter
from pathlib import Path

import yaml

CONFIG_PATH = Path(os.getenv("VISION_CONFIG", "agents/vision/config.yaml"))
SPLITS = ("train", "valid", "test")


def merged_name(info: dict) -> str:
    return f"{info['part']}-{info['damage_type']}"


def main() -> None:
    cfg = yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8"))
    src = Path(cfg["split"]["output_dir"])
    out = Path(cfg["merged"]["output_dir"])
    mapping = yaml.safe_load(Path(cfg["class_mapping"]).read_text(encoding="utf-8"))

    old_names = yaml.safe_load((src / "data.yaml").read_text(encoding="utf-8"))["names"]
    old_names = list(old_names.values()) if isinstance(old_names, dict) else list(old_names)
    new_names = sorted({merged_name(mapping[n]) for n in old_names})
    old_to_new = {i: new_names.index(merged_name(mapping[n])) for i, n in enumerate(old_names)}

    if out.exists():
        shutil.rmtree(out)
    counts = {s: Counter() for s in SPLITS}
    for split in SPLITS:
        (out / split / "labels").mkdir(parents=True)
        shutil.copytree(src / split / "images", out / split / "images")
        for label in sorted((src / split / "labels").glob("*.txt")):
            lines = []
            for line in label.read_text(encoding="utf-8").splitlines():
                if line.strip():
                    cls, *coords = line.split()
                    new_cls = old_to_new[int(cls)]
                    lines.append(" ".join([str(new_cls), *coords]))
                    counts[split][new_names[new_cls]] += 1
            (out / split / "labels" / label.name).write_text("\n".join(lines) + "\n",
                                                            encoding="utf-8")

    data_yaml = {"train": "train/images", "val": "valid/images", "test": "test/images",
                 "nc": len(new_names), "names": new_names}
    (out / "data.yaml").write_text(yaml.safe_dump(data_yaml, sort_keys=False), encoding="utf-8")

    # Mapping for the agent: merged class -> Damage fields (no severity hint anymore).
    merged_mapping = {n: {"part": n.split("-")[0], "damage_type": n.split("-")[1],
                          "severity_hint": None} for n in new_names}
    Path(cfg["merged"]["class_mapping"]).write_text(
        "# Generated by agents/vision/merge_classes.py: merged class -> Damage fields\n"
        + yaml.safe_dump(merged_mapping, sort_keys=True), encoding="utf-8")

    print(f"{len(old_names)} classes -> {len(new_names)} merged classes")
    print("Boxes per class (train / valid / test):")
    for name in new_names:
        print(f"  {name:22s} " + " ".join(f"{counts[s][name]:5d}" for s in SPLITS))
    print(f"\nWritten to {out} and {cfg['merged']['class_mapping']}")


if __name__ == "__main__":
    main()